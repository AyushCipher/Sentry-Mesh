"""Layer 1 - the shared, append-only event log.

WHY A REDIS STREAM AND NOT A LIST
---------------------------------
The log is written with ``XADD`` into a Redis *stream*, not ``RPUSH`` into a
list, for three reasons that matter to this system specifically:

1. **Server-assigned, monotonic, globally-ordered IDs.**  A stream entry ID
   (``<ms>-<seq>``) is generated by Redis itself, so two specialists appending
   concurrently from an ``asyncio.gather`` cannot produce an ambiguous
   ordering.  With a list we would have to invent our own ordering key and
   defend it under concurrency.
2. **Range reads by ID.**  ``XRANGE key (last_id +`` gives "everything that
   happened after the last event the dashboard saw" in one call.  That is
   exactly the primitive the live trace view and ``get_case_trace(after=...)``
   need; a list only offers positional indexes, which shift meaning if the log
   is ever trimmed.
3. **Consumer groups are available later.**  Nothing in v1 uses ``XGROUP``, but
   fanning the same log out to an alerting worker or a warehouse sink is a
   configuration change rather than a rewrite.

SINGLE SOURCE OF TRUTH
----------------------
``sentrymesh:events`` is *the* log.  ``sentrymesh:case:{id}:events`` is a
derived index holding the stream IDs for one case, so that reconstructing a
single case is O(events-in-case) instead of a full-stream scan.  The index is
written in the same atomic Lua call as the ``XADD``, so it can never drift, and
:meth:`EventLog.rebuild_case_index` proves it is derived by regenerating it
from the stream alone.

No agent in this system holds private state that is not also written here.
"""

from __future__ import annotations

import asyncio
import json
import uuid
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from typing import Any, AsyncIterator, Dict, List, Optional, Tuple

from sentrymesh.config import CASE_INDEX_KEY, SETTINGS, STREAM_KEY

# The five event types the architecture is specified around, plus two
# operational types that keep the log honest: a case-open marker so a trace has
# a beginning, and an error type so a failed run is a first-class recorded fact
# rather than a silent gap in the audit trail.
ALLOWED_EVENT_TYPES = frozenset(
    {
        "tool_call",
        "finding",
        "verdict",
        "escalation",
        "human_decision",
        "case_opened",
        "error",
    }
)

ALLOWED_ACTOR_PREFIXES = ("supervisor", "human_reviewer", "harness")


def _utcnow() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


@dataclass
class Event:
    """One immutable entry in the shared log."""

    case_id: str
    actor: str
    event_type: str
    payload: Dict[str, Any] = field(default_factory=dict)
    timestamp: str = field(default_factory=_utcnow)
    event_id: str = ""  # assigned by the log on append

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_stored(cls, event_id: str, raw: str) -> "Event":
        data = json.loads(raw)
        data["event_id"] = event_id
        return cls(**data)


class _InMemoryStreamBackend:
    """A faithful subset of the Redis stream operations SentryMesh uses.

    This exists so the test-suite and a laptop demo do not require a running
    Redis server.  It implements the same ``<ms>-<seq>`` ID scheme and the same
    atomic append-plus-index operation.  It is NOT a general Redis emulator and
    it is not durable - :attr:`EventLog.backend` reports ``in_memory`` so that
    the API ``/health`` endpoint and the harness report always disclose which
    backend produced a given run.
    """

    name = "in_memory"

    def __init__(self) -> None:
        self._stream: List[Tuple[str, str]] = []
        self._index: Dict[str, List[str]] = {}
        self._last_ms = 0
        self._last_seq = 0
        self._lock = asyncio.Lock()

    def _next_id(self) -> str:
        ms = int(datetime.now(timezone.utc).timestamp() * 1000)
        if ms == self._last_ms:
            self._last_seq += 1
        else:
            self._last_ms, self._last_seq = ms, 0
        return f"{self._last_ms}-{self._last_seq}"

    async def append(self, case_id: str, raw: str) -> str:
        async with self._lock:
            event_id = self._next_id()
            self._stream.append((event_id, raw))
            self._index.setdefault(case_id, []).append(event_id)
            return event_id

    async def read_case(self, case_id: str, after: Optional[str]) -> List[Tuple[str, str]]:
        ids = set(self._index.get(case_id, []))
        out = [(eid, raw) for eid, raw in self._stream if eid in ids]
        if after:
            out = [(eid, raw) for eid, raw in out if _id_gt(eid, after)]
        return out

    async def read_all(self, after: Optional[str], limit: int) -> List[Tuple[str, str]]:
        out = list(self._stream)
        if after:
            out = [(eid, raw) for eid, raw in out if _id_gt(eid, after)]
        return out[-limit:] if limit else out

    async def case_ids(self) -> List[str]:
        return list(self._index.keys())

    async def rebuild_index(self) -> int:
        self._index = {}
        for eid, raw in self._stream:
            self._index.setdefault(json.loads(raw)["case_id"], []).append(eid)
        return len(self._stream)

    async def ping(self) -> bool:
        return True

    async def close(self) -> None:
        return None


class _RedisStreamBackend:
    """Real Redis Streams backend."""

    name = "redis"

    # Append and index-update in one atomic server-side call.  Doing this in a
    # MULTI/EXEC is not possible because the RPUSH needs the ID that XADD only
    # returns at EXEC time; a Lua script sees it immediately.
    _APPEND_LUA = """
    local id = redis.call('XADD', KEYS[1], '*', 'event', ARGV[1])
    redis.call('RPUSH', KEYS[2], id)
    return id
    """

    def __init__(self, client: Any) -> None:
        self._r = client
        self._append = client.register_script(self._APPEND_LUA)

    async def append(self, case_id: str, raw: str) -> str:
        event_id = await self._append(
            keys=[STREAM_KEY, CASE_INDEX_KEY.format(case_id=case_id)], args=[raw]
        )
        return event_id.decode() if isinstance(event_id, bytes) else str(event_id)

    async def read_case(self, case_id: str, after: Optional[str]) -> List[Tuple[str, str]]:
        ids = await self._r.lrange(CASE_INDEX_KEY.format(case_id=case_id), 0, -1)
        ids = [i.decode() if isinstance(i, bytes) else i for i in ids]
        if after:
            ids = [i for i in ids if _id_gt(i, after)]
        if not ids:
            return []
        pipe = self._r.pipeline()
        for eid in ids:
            pipe.xrange(STREAM_KEY, min=eid, max=eid)
        chunks = await pipe.execute()
        return [_decode_entry(entry) for chunk in chunks for entry in chunk]

    async def read_all(self, after: Optional[str], limit: int) -> List[Tuple[str, str]]:
        start = f"({after}" if after else "-"
        entries = await self._r.xrange(STREAM_KEY, min=start, max="+", count=limit or None)
        return [_decode_entry(e) for e in entries]

    async def case_ids(self) -> List[str]:
        found: List[str] = []
        pattern = CASE_INDEX_KEY.format(case_id="*")
        async for key in self._r.scan_iter(match=pattern, count=200):
            key = key.decode() if isinstance(key, bytes) else key
            found.append(key.split(":")[2])
        return found

    async def rebuild_index(self) -> int:
        """Regenerate every per-case index from the stream alone.

        Demonstrates that the index is derived state: deleting it loses nothing.
        """
        pattern = CASE_INDEX_KEY.format(case_id="*")
        stale = [k async for k in self._r.scan_iter(match=pattern, count=200)]
        if stale:
            await self._r.delete(*stale)
        entries = await self._r.xrange(STREAM_KEY, min="-", max="+")
        count = 0
        pipe = self._r.pipeline()
        for entry in entries:
            eid, raw = _decode_entry(entry)
            case_id = json.loads(raw)["case_id"]
            pipe.rpush(CASE_INDEX_KEY.format(case_id=case_id), eid)
            count += 1
        await pipe.execute()
        return count

    async def ping(self) -> bool:
        return bool(await self._r.ping())

    async def close(self) -> None:
        await self._r.aclose()


def _decode_entry(entry: Any) -> Tuple[str, str]:
    eid, fields = entry
    eid = eid.decode() if isinstance(eid, bytes) else eid
    raw = fields.get(b"event") if b"event" in fields else fields.get("event")
    if isinstance(raw, bytes):
        raw = raw.decode()
    return eid, raw


def _id_gt(a: str, b: str) -> bool:
    """Compare two ``<ms>-<seq>`` stream IDs numerically."""

    def parts(x: str) -> Tuple[int, int]:
        ms, _, seq = x.partition("-")
        return int(ms), int(seq or 0)

    return parts(a) > parts(b)


class EventLog:
    """Append-only shared state for every agent, the API and the dashboard."""

    def __init__(self, backend: Any, downgrade_reason: Optional[str] = None) -> None:
        self._backend = backend
        # Why we are not on Redis, when we are not on Redis. Surfaced through
        # /health and the harness report so the downgrade is never silent - a
        # run whose audit trail evaporates at process exit must say so.
        self.downgrade_reason = downgrade_reason

    @property
    def backend(self) -> str:
        return self._backend.name

    # -- construction ------------------------------------------------------
    @classmethod
    async def connect(cls, redis_url: Optional[str] = None, *, require_redis: Optional[bool] = None) -> "EventLog":
        """Connect to Redis, or fall back to the in-memory backend.

        With ``SENTRYMESH_REQUIRE_REDIS=1`` a missing server is a hard error
        instead of a silent downgrade - which is what you want in production and
        not what you want on a laptop, hence the switch.
        """
        url = redis_url or SETTINGS.redis_url
        strict = SETTINGS.require_redis if require_redis is None else require_redis
        try:
            import redis.asyncio as aioredis

            # 10s, not 2s: a dual-stack host that tries ::1 before 127.0.0.1
            # spends the whole budget on the dead IPv6 attempt, and a too-tight
            # timeout turns "resolution is slow" into "Redis is down".
            client = aioredis.from_url(url, socket_connect_timeout=10, socket_timeout=10)
            await client.ping()
            return cls(_RedisStreamBackend(client))
        except Exception as exc:  # noqa: BLE001 - any connection failure downgrades
            if strict:
                raise RuntimeError(f"SENTRYMESH_REQUIRE_REDIS=1 but Redis at {url} is unreachable: {exc}") from exc
            return cls(
                _InMemoryStreamBackend(),
                downgrade_reason=f"Redis at {url} unreachable ({type(exc).__name__}: {exc}); "
                "the event log is in-memory and will not survive this process",
            )

    @classmethod
    def in_memory(cls) -> "EventLog":
        return cls(_InMemoryStreamBackend())

    # -- writes ------------------------------------------------------------
    async def append(
        self,
        case_id: str,
        actor: str,
        event_type: str,
        payload: Optional[Dict[str, Any]] = None,
    ) -> Event:
        if event_type not in ALLOWED_EVENT_TYPES:
            raise ValueError(f"unknown event_type {event_type!r}; allowed: {sorted(ALLOWED_EVENT_TYPES)}")
        if not case_id:
            raise ValueError("case_id is required - every event belongs to a case")
        if not actor:
            raise ValueError("actor is required - every event has an accountable author")

        event = Event(case_id=case_id, actor=actor, event_type=event_type, payload=payload or {})
        raw = json.dumps(
            {
                "case_id": event.case_id,
                "actor": event.actor,
                "event_type": event.event_type,
                "payload": event.payload,
                "timestamp": event.timestamp,
            },
            default=str,
        )
        event.event_id = await self._backend.append(case_id, raw)
        return event

    # -- reads -------------------------------------------------------------
    async def get_case_trace(self, case_id: str, *, after: Optional[str] = None) -> List[Event]:
        """Reconstruct the full ordered history of one case.

        This is the only read path used by the audit trail, the case-detail
        page and the live trace view - so the dashboard is, by construction,
        showing the same thing an auditor would see.
        """
        rows = await self._backend.read_case(case_id, after)
        events = [Event.from_stored(eid, raw) for eid, raw in rows]
        events.sort(key=lambda e: (int(e.event_id.split("-")[0]), int(e.event_id.split("-")[1])))
        return events

    async def get_recent(self, *, after: Optional[str] = None, limit: int = 200) -> List[Event]:
        rows = await self._backend.read_all(after, limit)
        return [Event.from_stored(eid, raw) for eid, raw in rows]

    async def known_case_ids(self) -> List[str]:
        return sorted(await self._backend.case_ids())

    async def rebuild_case_index(self) -> int:
        return await self._backend.rebuild_index()

    async def ping(self) -> bool:
        try:
            return await self._backend.ping()
        except Exception:  # noqa: BLE001
            return False

    async def close(self) -> None:
        await self._backend.close()

    # -- live tail ---------------------------------------------------------
    async def follow(
        self,
        case_id: str,
        *,
        after: Optional[str] = None,
        poll_interval: float = 0.25,
        idle_timeout: float = 300.0,
    ) -> AsyncIterator[Event]:
        """Yield new events for a case as they are appended.

        Implemented as a poll over ``get_case_trace(after=...)`` rather than
        ``XREAD BLOCK``.  The per-case index is a list, so a blocking read would
        have to tail the *global* stream and filter, which costs more code than
        it saves at this event volume.  Named as a known limitation in the
        README; swapping in ``XREAD BLOCK`` is a change local to this method.
        """
        cursor = after
        idle = 0.0
        while idle < idle_timeout:
            batch = await self.get_case_trace(case_id, after=cursor)
            if batch:
                idle = 0.0
                for event in batch:
                    cursor = event.event_id
                    yield event
            else:
                await asyncio.sleep(poll_interval)
                idle += poll_interval


def new_case_id(prefix: str = "case") -> str:
    return f"{prefix}-{uuid.uuid4().hex[:10]}"
