"""Regenerate the 'Held-out evaluation' section of the top-level README.md.

Every number is read from eval/heldout/results/{heldout_summary,tuning}.json and
the run manifests / cache - nothing is typed in by hand.  Run after
`python eval/run_heldout.py report` and `... tune`:

    python eval/heldout/make_readme_section.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "eval" / "heldout" / "results"
README = ROOT / "README.md"
START, END = "<!-- HELDOUT:START (generated by eval/heldout/make_readme_section.py) -->", "<!-- HELDOUT:END -->"


def f(x, pct=False):
    if x is None:
        return "n/a"
    return f"{x * 100:.1f}%" if pct else f"{x:.3f}"


def cell(m, key, pct=False):
    e = m.get(key)
    if not e:
        return "n/a"
    ci = e.get("ci95")
    pt = f(e["point"], pct)
    return pt if not ci else f"{pt} [{f(ci[0], pct)}, {f(ci[1], pct)}]"


ROWS = [("Precision (auto-only)", "precision_auto_only", False), ("Recall (auto-only)", "recall_auto_only", False),
        ("F1 (auto-only)", "f1_auto_only", False), ("Precision (escalation = flag)", "precision_escalation_as_flag", False),
        ("Recall (escalation = flag)", "recall_escalation_as_flag", False), ("F1 (escalation = flag)", "f1_escalation_as_flag", False),
        ("FPR (auto-only)", "fpr_auto_only", False), ("FPR (escalation = flag)", "fpr_escalation_as_flag", False),
        ("Escalation rate (all)", "escalation_rate", True), ("Escalation rate on ambiguous", "escalation_rate_on_ambiguous", True),
        ("Escalation rate on decisive", "escalation_rate_on_decisive", True), ("Auto-resolve rate", "auto_resolve_rate", True),
        ("Auto-resolve accuracy (ambiguous auto-resolved = wrong)", "auto_resolve_accuracy_all", True),
        ("Auto-resolve accuracy (decisive cases only)", "auto_resolve_accuracy_decisive_only", True),
        ("Fraud cases auto-approved", "fraud_auto_approved_rate", True)]


def table(cols):
    head = "| Metric | " + " | ".join(n for n, _ in cols) + " |\n|---|" + "---|" * len(cols) + "\n"
    body = ""
    for label, key, pct in ROWS:
        body += f"| {label} | " + " | ".join(cell(m, key, pct) for _, m in cols) + " |\n"
    return head + body


def main() -> None:
    s = json.loads((RES / "heldout_summary.json").read_text(encoding="utf-8"))
    out = [START, "", "## Held-out evaluation", ""]
    out.append("Synthetic, LLM-authored set of 121 cases (48 fraud / 51 legitimate / 22 ambiguous, 18 with injected instructions) with a "
               "precedent corpus disjoint from the original one. See `eval/heldout/README.md` for the rubric. "
               "Generated by `eval/heldout/make_readme_section.py` from the saved files in `eval/heldout/results/`; "
               "brackets are 95% cluster-bootstrap CIs over cases.")
    out.append("")
    live = s.get("heldout_live")
    off = s.get("heldout_offline")
    cache_lines = sum(1 for _ in (RES / "llm_cache" / "heldout.jsonl").open(encoding="utf-8")) if (RES / "llm_cache" / "heldout.jsonl").exists() else 0
    if live:
        man = live.get("run_manifest") or {}
        out.append(f"### Live LLM run (real model, full multi-agent pipeline)")
        out.append("")
        q = json.loads((RES / "provider_quota_notes.json").read_text(encoding="utf-8"))
        out.append(f"* Model: `{man.get('model')}` via `{man.get('provider_host')}` (the configured model `{q['configured_model']['name']}` hit the provider's "
                   f"free-tier cap of {q['configured_model']['limit_per_day']} requests/day after ~20 calls, so the run used `{q['fallback_model_used']['name']}` "
                   f"(provider resolves it to `{q['fallback_model_used']['resolved_by_provider_error_to']}`, free-tier cap {q['fallback_model_used']['limit_per_day']} requests/day) on the same key; "
                   "numbers are for that model only).")
        runs = man.get("runs", [])
        out.append("* Completed cases per repeat (of 121): " + ", ".join(f"rep{r['repeat']}={r['on_disk_total']}" for r in runs)
                   + "; cases not run / aborted: " + ", ".join(f"rep{r['repeat']}={r['not_run_or_aborted_due_to_budget']}" for r in runs)
                   + "; the run stopped early: " + ("yes, provider per-day request quota exhausted (see eval/heldout/results/provider_quota_notes.json)" if any(r['not_run_or_aborted_due_to_budget'] for r in runs) else "no") + ". Repeats 2 and 3 were NOT run (requested 3).")
        out.append(f"* Rows on disk per repeat: {live['repeats_on_disk']}; unique cases: {live['unique_cases']}; rows with at least one "
                   f"specialist/supervisor error: {live['rows_with_any_run_error']}; error classes: {live['error_classes'] or 'none'}.")
        b = man.get("budget", {})
        out.append(f"* Last invocation: {b.get('live_calls')} live calls, {b.get('cache_hits')} cache hits, {b.get('retries')} retries, "
                   f"{b.get('input_tokens')} input / {b.get('output_tokens_incl_reasoning')} output tokens, estimated cost "
                   f"${b.get('estimated_cost_usd')} at an ASSUMED ${b.get('assumed_price_per_million', {}).get('input')}/"
                   f"${b.get('assumed_price_per_million', {}).get('output')} per million tokens (actual billed cost is $0: free-tier key). "
                   f"Total provider responses saved in the on-disk cache across all invocations: {cache_lines}.")
        stab = live.get("decision_stability_across_repeats")
        if stab:
            out.append(f"* Decision stability across repeats: {stab['identical_decision_across_repeats']}/{stab['cases_with_all_repeats']} "
                       f"cases got the identical decision in every repeat.")
        adv = live["adversarial"]
        out.append(f"* Injection cases: {adv['rows']} rows, injected instruction achieved its target decision in {adv['injection_succeeded_rows']} rows "
                   f"(decisions on those rows: {adv['decisions']}).")
        out.append("")
    cols = []
    if live:
        cols.append(("Live LLM, all rows", live["pooled"]))
        if live.get("split_test"):
            cols.append(("Live LLM, test split", live["split_test"]))
    if off:
        cols.append((f"Offline solver, same {off.get('matched_to_live_case_count')} cases", off["matched_to_live_cases"]) if "matched_to_live_cases" in off else ("Offline solver (no LLM)", off["pooled"]))
    if cols:
        out.append(table(cols))
        out.append("")
        if live:
            n = live["pooled"]["n_rows"]["point"]
            na = round(live["pooled"]["auto_resolve_rate"]["point"] * n)
            out.append(f"Zero-width intervals ([1.000, 1.000], [0.000, 0.000]) are a small-sample artifact, not certainty: only {na} of {n} live rows were auto-resolved, "
                       f"and 0 errors in {na} trials is still compatible with a true error rate up to about {3 / na:.0%} (rule of three). "
                       "The offline column here is on only these cases, so its intervals are wide too.")
            out.append("")
            out.append("Decision counts by true label (live, all rows): " + "; ".join(f"{t}: {d}" for t, d in live["decision_counts_by_truth"].items()) + ".")
            out.append("")
    if off:
        out.append(f"The offline column is the deterministic scoring-function fallback restricted to the same cases the live run completed (a number about the scoring code, not an LLM). "
                   f"On all {off['unique_cases']} held-out cases it gets: precision (auto-only) {cell(off['pooled'], 'precision_auto_only')}, recall (auto-only) {cell(off['pooled'], 'recall_auto_only')}, "
                   f"escalation rate {cell(off['pooled'], 'escalation_rate', True)}, FPR (escalation = flag) {cell(off['pooled'], 'fpr_escalation_as_flag')}.")
        out.append("")
    if "bank_live" in s:
        bl = s["bank_live"]
        out.append(f"Original 23-case bank, live run: {bl['unique_cases']} cases, {bl['repeats_on_disk']} rows; "
                   f"escalation rate {cell(bl['pooled'], 'escalation_rate', True)}, precision (auto-only) {cell(bl['pooled'], 'precision_auto_only')}, "
                   f"recall (auto-only) {cell(bl['pooled'], 'recall_auto_only')}, FPR (auto-only) {cell(bl['pooled'], 'fpr_auto_only')}.")
        out.append("")
    t = RES / "tuning.json"
    if t.exists():
        tu = json.loads(t.read_text(encoding="utf-8"))
        sel, d = tu["selected"], tu["default"]
        out.append("### Threshold validation (dev split only, evaluated on test)")
        out.append("")
        out.append(f"Grid search over `risk_floor_factor` and `max_model_risk_divergence` on the {tu['dev_cases']} dev cases ({tu['dev_rows']} rows), "
                   f"replaying the saved supervisor outputs (no new LLM calls; replay reproduces {tu['rows_checked'] - tu['replay_sanity_default_thresholds_decision_mismatches']}"
                   f"/{tu['rows_checked']} recorded decisions at the defaults). Cost function: false approve 10, false decline 5, escalating a decisive case 1, "
                   f"auto-resolving an ambiguous case 3.")
        out.append("")
        out.append(f"* Default ({d['risk_floor_factor']}, {d['max_model_risk_divergence']}) -> selected ({sel['risk_floor_factor']}, {sel['max_model_risk_divergence']}); "
                   f"changed: {sel['changed_from_default']}.")
        out.append("")
        ba = tu["bounding_activity_at_default"]
        out.append(f"At the defaults, the bounding logic acted on {ba['rows_with_any_policy_override']}/{ba['rows_total']} live rows "
                   f"(floor raised: {ba['rows_floor_raised']}, divergence-forced escalation: {ba['rows_divergence_forced_escalation']}). "
                   "If the selected point equals the default, the dev split gave no evidence for moving the thresholds (ties resolve to the default); "
                   "that is a non-result, not a validation of 0.9 / 30.")
        out.append("")
        out.append("| Split | Before: cost/row | After: cost/row | Before: escalation | After: escalation | Before: fraud auto-approved | After: fraud auto-approved |\n|---|---|---|---|---|---|---|")
        for sp in ("dev", "test"):
            b, a = tu[f"{sp}_before"], tu[f"{sp}_after"]
            out.append(f"| {sp} ({b['n_rows']} rows) | {b['cost_per_row']} | {a['cost_per_row']} | {f(b['metrics']['escalation_rate'], True)} | "
                       f"{f(a['metrics']['escalation_rate'], True)} | {f(b['metrics']['fraud_auto_approved_rate'], True)} | {f(a['metrics']['fraud_auto_approved_rate'], True)} |")
        dd = tu["test_cost_per_row_diff_tuned_minus_default"]
        out.append("")
        out.append(f"Test-split cost/row difference (tuned minus default), paired bootstrap over cases: {dd['mean']} (95% CI [{dd['ci95'][0]}, {dd['ci95'][1]}]). "
                   f"{'The interval spans zero: no demonstrated benefit.' if dd['ci95'][0] <= 0 <= dd['ci95'][1] else 'The interval excludes zero.'}")
        out.append("")
    out.append("### Limitations (honest)")
    out.append("")
    out.append("* The set is synthetic and written by an LLM that also wrote the labels, rubric and precedents. It removes code-level circularity "
               "with the original bank (separate generator, no solver-keyed fields, disjoint precedents) but not author-level circularity. "
               "It says nothing about performance on real fraud; real base rates are far lower, so real-world precision would be much lower than shown.")
    out.append("* Intervals are wide at this size (121 cases; subgroups smaller). Free-tier daily quotas, not the code, bound how much live data exists.")
    out.append("* Numbers are for one specific model (above) and the stated number of repeats; any case that did not finish is counted as not run, not extrapolated.")
    out.append("* Threshold tuning used the small dev split only; the whole set was visible to its author, so the test split is not a blind holdout.")
    out.append("")
    out.append(END)
    block = "\n".join(out) + "\n"
    text = README.read_text(encoding="utf-8")
    if START in text and END in text:
        pre, rest = text.split(START, 1)
        _, post = rest.split(END, 1)
        text = pre + block.rstrip("\n") + post
    else:
        text = text.rstrip("\n") + "\n\n" + block
    README.write_text(text, encoding="utf-8", newline="\n")
    print("README updated")


if __name__ == "__main__":
    main()
